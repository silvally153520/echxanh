const getPropertyCategory = (title: string) => (
  villaTitles.has(title) ? 'VILLA' : resortTitles.has(title) ? 'RESORT' : 'HOTEL'
);

const seedProperties = async () => {
  const hostPasswordHash = await bcrypt.hash(randomBytes(32).toString('hex'), 12);
  const host = await prisma.user.upsert({
    where: { email: sampleHostEmail },
    create: {
      email: sampleHostEmail,
      passwordHash: hostPasswordHash,
      name: 'sieuechxanh Host mẫu',
      role: 'HOST',
    },
    update: { role: 'HOST', isBanned: false },
    select: { id: true },
  });

  await prisma.$transaction(properties.map(property => prisma.property.updateMany({
    where: { title: property.title, city: property.city },
    data: { category: getPropertyCategory(property.title) },
  })));

  let created = 0;
  for (const property of additionalProperties) {
    const existing = await prisma.property.findFirst({
      where: { hostId: host.id, title: property.title },
      select: { id: true },
    });

    if (existing) continue;

    await prisma.property.create({
      data: {
        ...property,
        hostId: host.id,
        country: 'Việt Nam',
        category: getPropertyCategory(property.title),
        images: [],
        status: 'ACTIVE',
      },
    });
    created += 1;
  }

  const totalActive = await prisma.property.count({ where: { status: 'ACTIVE' } });
  console.info(`Additional sample listings ready. Created ${created} new listings; ${totalActive} active listings are available.`);
};

seedProperties()
  .catch(error => {
    console.error('Failed to seed sample properties:', error);
    process.exitCode = 1;
  })
  .finally(async () => prisma.$disconnect());
